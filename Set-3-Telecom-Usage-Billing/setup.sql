USE master;
GO
IF DB_ID('TelecomDB') IS NOT NULL
BEGIN
    ALTER DATABASE TelecomDB SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE TelecomDB;
END
GO
CREATE DATABASE TelecomDB;
GO
USE TelecomDB;
GO
CREATE TABLE circles (
    circle_id    INT PRIMARY KEY,
    circle_code  CHAR(2)     NOT NULL UNIQUE,
    circle_name  VARCHAR(40) NOT NULL
);
CREATE TABLE plans (
    plan_id        INT PRIMARY KEY,
    plan_name      VARCHAR(30)   NOT NULL,
    monthly_fee    DECIMAL(8,2)  NOT NULL,
    data_limit_gb  INT           NOT NULL          -- data allowed per month
);
CREATE TABLE subscribers (
    subscriber_id  INT PRIMARY KEY,
    msisdn         CHAR(10)    NOT NULL UNIQUE,
    full_name      VARCHAR(60) NOT NULL,
    circle_id      INT         NOT NULL REFERENCES circles(circle_id),
    plan_id        INT         NOT NULL REFERENCES plans(plan_id),
    activated_on   DATE        NOT NULL
);
CREATE TABLE call_records (
    record_id      INT IDENTITY(1,1) PRIMARY KEY,
    subscriber_id  INT          NOT NULL REFERENCES subscribers(subscriber_id),
    record_type    VARCHAR(5)   NOT NULL CHECK (record_type IN ('VOICE', 'DATA')),
    started_at     DATETIME2(0) NOT NULL,
    duration_sec   INT          NULL,      -- voice calls
    data_mb        DECIMAL(10,1) NULL      -- data sessions
);
CREATE TABLE invoices (
    invoice_id     INT PRIMARY KEY,
    subscriber_id  INT           NOT NULL REFERENCES subscribers(subscriber_id),
    bill_month     DATE          NOT NULL,
    invoice_date   DATE          NOT NULL,
    due_date       DATE          NOT NULL,
    amount         DECIMAL(10,2) NOT NULL CHECK (amount >= 0),
    paid_on        DATE          NULL      -- NULL = not paid yet
);
GO

